// アプリ全体で使うドメイン型。
// バンドルされた読み取り専用データ（kanji.json / words.json。scripts/build-data.mjs が作る）と
// Dexie に保存するユーザーデータの両方で共有する。

/** 字の韓国語の訓と音（훈음）。學 → 배울 학。 */
export interface KoreanSound {
  /** 訓：字の意味を表す韓国語（배울）。無い字もある。 */
  hun?: string;
  /** 音：字の韓国語の音（학）。 */
  eum: string;
}

/** 漢字1字の辞書エントリ（日本の字で引く）。 */
export interface KanjiData {
  /** 漢字1字（日本の字）。例: "学" */
  char: string;
  /** 韓国で書く形（字形が違うときだけ）。例: 学 → "學" */
  ko?: string;
  /** 韓国語の訓と音。音が二つ以上ある字もある（樂 락・악）。 */
  sounds: KoreanSound[];
  /** 音読み（カタカナ。語でよく使う順）。例: ["ガク"] */
  on?: string[];
  /** 訓読み（KANJIDIC の形。送り仮名の前に点：まな.ぶ）。 */
  kun?: string[];
  /** 意味（英語）。 */
  meaning: string;
  strokes: number;
  /** 日本の学年（1〜6。8 は中学で習う常用漢字）。 */
  grade?: number;
  /** 常用漢字（2136字）の一つ。 */
  joyo?: boolean;
  /** JLPT の級（5＝N5 … 1＝N1）。 */
  n?: number;
  /** 韓国の基礎漢字（교육용 기초 한자 1800字）の一つ。 */
  edu?: boolean;
}

/** 日本語の語1語（漢字の入った語）の辞書エントリ。 */
export interface WordData {
  /** 表記。例: "学生"・"食べる" */
  kanji: string;
  /** 読み（ひらがな。外来語の部分はカタカナのことも）。例: "がくせい" */
  kana: string;
  /**
   * 字ごとの、この語での読み（字の並び順。々 は前の字の分）。例: 学校 → ["がっ","こう"]、食べる → ["た"]。
   * 熟字訓（今日 きょう・大人 おとな）のように字に分けられない語には無い。
   */
  rt?: string[];
  /** 字ごとのふだんの読み（rt と違う字があるときだけ）。例: 学校 → ["がく","こう"] */
  base?: string[];
  /** この語だけの特別な読みの字（rt の番号）。 */
  odd?: number[];
  /** 意味（韓国語。en なら英語）。例: "학생" */
  gloss: string;
  en?: boolean;
  /** 同じ漢字の韓国語の語（학생 學生 ↔ 学生）。意味の違う語もある（工夫 くふう ↔ 공부）。 */
  ko?: string;
  /** ko と意味も同じ（韓国語の漢字語が、そのまま日本語の語になる）。 */
  ks?: boolean;
  /** ko をどれくらいよく使うか（1 초급・2 중급・3 고급・4 字幕でよく使う・5 ほとんど使わない）。 */
  kl?: number;
  /**
   * ko との、意味・使い方のちがい（韓国語で。手で確かめた語だけ）。例: 洋服 → "일본어에서는 옷 전반을 말해요. 한국어 '양복'(정장)은 スーツ라고 해요."
   */
  kd?: string;
  /** JLPT の級（5＝N5 … 1＝N1）。 */
  n?: number;
  /** 学ぶ順の目安：1 N5・N4、2 N3、3 N2・N1・よく使う語、4 字幕でよく使う語・韓国語でもよく使う漢字語、5 ほとんど使わない語。 */
  lv?: number;
  /** 映画・ドラマの字幕の日本語で、100万語あたり何回使うか。 */
  fq?: number;
}

/** 解決済みの語（語 + 字）。resolver の出力。 */
export interface ResolvedWord extends WordData {
  /** 字（表記の漢字を1字ずつ。々 は前の字）。rt と同じ並び。 */
  chars: string[];
  /** 解決元: seed=辞書, manual=手で登録。 */
  source: "seed" | "manual";
}
